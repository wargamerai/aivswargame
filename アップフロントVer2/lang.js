const LANG_PATTERNS = [];
LANG_PATTERNS_SRC.forEach(([ja, en]) => {
  if (!/\{\d+#?\}/.test(ja)) { LANG_EXACT[ja] = en; return; }
  const keys = [];
  const body = ja.split(/(\{\d+#?\})/).map(part => {
    const m = part.match(/^\{(\d+)(#?)\}$/);
    if (m) { keys.push(+m[1]); return m[2] ? '([-+]?\\d+)' : '([\\s\\S]+?)'; }
    return part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  }).join('');
  LANG_PATTERNS.push({ re: new RegExp('^' + body + '$'), keys, en, lit: ja.replace(/\{\d+#?\}/g, '').length });
});
LANG_PATTERNS.sort((a, b) => b.lit - a.lit); // 決まった文字の多い（具体的な）型から先に試す
// 文の型に当てはまれば英語にする（当てはまらなければ null）
function langMatchPattern(core){
  for (const p of LANG_PATTERNS) {
    const m = core.match(p.re);
    if (!m) continue;
    let out = p.en;
    p.keys.forEach((k, i) => { out = out.split('{' + k + '}').join(langTranslate(m[i + 1])); });
    return out;
  }
  return null;
}

const LANG_JP = /[぀-ヿ一-鿿！-｠　-〿]/;
const LANG_TERM_RE = new RegExp(
  Object.keys(LANG_TERMS).sort((a, b) => b.length - a.length).map(k => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
const langCache = new Map();

// 日本語の文字列を英語にする
function langTranslate(s){
  if(!LANG_JP.test(s)) return s;
  if(langCache.has(s)) return langCache.get(s);
  const lead = s.match(/^\s*/)[0], trail = s.match(/\s*$/)[0];
  const core = s.trim();
  let out, pm;
  if(core.indexOf('\n') >= 0){
    // 複数行のメッセージは 1行ずつ訳す
    out = core.split('\n').map(l => langTranslate(l)).join('\n');
  } else if(LANG_EXACT[core] !== undefined){
    out = LANG_EXACT[core];
  } else if((pm = langMatchPattern(core)) !== null){
    out = pm;
  } else {
    // 語句を置き換え、英単語どうしや数字と続くところに空白を入れる
    out = '';
    let last = 0, m, prevTerm = false;
    LANG_TERM_RE.lastIndex = 0;
    while((m = LANG_TERM_RE.exec(core))){
      const raw = core.slice(last, m.index);
      if(raw){
        if(prevTerm && /[A-Za-z0-9)]$/.test(out) && /^[A-Za-z0-9]/.test(raw)) out += ' ';
        out += raw;
      }
      const en = LANG_TERMS[m[0]];
      if(/[A-Za-z0-9)\]]$/.test(out) && /^[A-Za-z0-9(]/.test(en)) out += ' ';
      out += en;
      last = m.index + m[0].length;
      prevTerm = true;
    }
    const rest = core.slice(last);
    if(rest && prevTerm && /[A-Za-z0-9)]$/.test(out) && /^[A-Za-z0-9]/.test(rest)) out += ' ';
    out += rest;
    out = out.replace(/ {2,}/g, ' ').replace(/ ([,.:;)\]?!])/g, '$1').replace(/\( /g, '(').trim();
  }
  out = lead + out + trail;
  langCache.set(s, out);
  return out;
}

