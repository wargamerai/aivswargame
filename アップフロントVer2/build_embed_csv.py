#!/usr/bin/env python3
"""Regenerate embedded_csv.js from CSV sources. Run after editing terrain/soldier CSV."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent
terrain = next(root.rglob("terrain_cards.csv"))
us = next(root.rglob("US_card_list.csv"))
ger = next(root.rglob("Germany_card_list.csv"))
rus = next(root.rglob("USSR_card_list.csv"))
jpn = next(root.rglob("Japan_card_list.csv"))
uk = next(root.rglob("Britain_card_list.csv"))

data = {
    "terrain": terrain.read_text(encoding="utf-8"),
    "us": us.read_text(encoding="utf-8"),
    "ger": ger.read_text(encoding="utf-8"),
    "rus": rus.read_text(encoding="utf-8"),
    "jpn": jpn.read_text(encoding="utf-8"),
    "uk":  uk.read_text(encoding="utf-8"),
}
out = root / "embedded_csv.js"
payload = json.dumps(data, ensure_ascii=False)
out.write_text(
    "/* Auto-generated by build_embed_csv.py — do not edit by hand */\n"
    "(function (global) {\n"
    "  'use strict';\n"
    f"  global.__EMBED_CSV__ = {payload};\n"
    "})(typeof window !== 'undefined' ? window : this);\n",
    encoding="utf-8",
)
print("Wrote", out, "(%d bytes)" % out.stat().st_size)
