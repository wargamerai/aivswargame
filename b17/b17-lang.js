  const hasJapanese = /[ぁ-ゖァ-ヺ一-龯]/;
  const quoteRegex = /[.*+?^${}()|[\]\\]/g;
  const phrases = new RegExp(Object.keys(messages).filter(key => key.length > 1)
    .sort((first, second) => second.length - first.length)
    .map(key => key.replace(quoteRegex, '\\$&')).join('|'), 'g');
  const patterns = [
    [/^第(\d+)波 · (\d+)回目$/, 'Wave $1 · Round $2'],
    [/^敵機接近 · 第(\d+)波$/, 'Enemy fighters inbound · Wave $1'],
    [/^護衛が排除できる敵機を選択 · 残り (\d+) 機$/, 'Choose a fighter to drive off · $1 remaining'],
    [/^残り (\d+) 件の被弾確認$/, '$1 hits left to inspect'],
    [/^（負傷・戦死 (\d+) 人）$/, '($1 wounded or killed)'],
    [/^([\s\S]+)へ向かいます。編隊内位置 (.+)。$/, 'Destination: $1. Formation position: $2.'],
    [/^目標は(.+)です。編隊では(.+)を飛びます。$/, 'The target is $1. We’re flying $2 in the formation.'],
    [/^ゾーン ?(\d+) ?に進入$/, 'Entering Zone $1'],
    [/^ゾーン ?(\d+)に入りました。$/, 'We’ve entered Zone $1.'],
    [/^(.+)に着陸$/, 'Land in $1'],
    [/^(.+)に降りるぞ$/, 'We’re landing in $1.'],
    [/^(.+)で脱出$/, 'Bail out over $1'],
    [/^(.+)で総員脱出！$/, 'Everyone bail out over $1!'],
    [/^(.+)に命中$/, 'Hit: $1'],
    [/^任務経験 (\d+)回$/, '$1 missions flown'],
    [/^(\d+) ?機撃墜$/, '$1 kills'],
    [/^第 ?(\d+) ?任務(.*)$/, 'Mission $1$2'],
    [/^(.*?)[\s　]?(\d+)発(.*)$/, '$1 $2 rounds$3'],
    [/^(.*?)[\s　]?(\d+)ターン(.*)$/, '$1 $2 turns$3'],
  ];

  function translate(value) {
    if (code !== 'en' || !hasJapanese.test(value)) return value;
    const text = value.trim();
    let result = messages[text];
    if (result === undefined && /[\r\n]/.test(text)) {
      result = text.split('\n').map(translate).join('\n');
    }
    if (result === undefined && text.includes(' ｜ ')) {
      result = text.split(' ｜ ').map(translate).join(' | ');
    }
    if (result === undefined) {
      for (const [pattern, format] of patterns) {
        if (!pattern.test(text)) continue;
        result = text.replace(pattern, format).replace(phrases, part => messages[part]);
        break;
      }
    }
    if (result === undefined) {
      result = text.replace(phrases, part => messages[part])
        .replace(/「([^」]+)」/g, '“$1”')
        .replace(/（/g, ' (').replace(/）/g, ')')
        .replace(/[、，]/g, ', ').replace(/。/g, '. ')
        .replace(/！/g, '! ').replace(/？/g, '? ')
        .replace(/[：]/g, ': ').replace(/・/g, ' · ')
        .replace(/ +/g, ' ').replace(/ ([.,?!])/g, '$1').trim();
    }
    return value.replace(text, () => result);
  }

  function localize(node) {
    if (code !== 'en') return;
    if (node.nodeType === Node.TEXT_NODE) {
      const translated = translate(node.nodeValue);
      if (node.nodeValue !== translated) node.nodeValue = translated;
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE || ['SCRIPT', 'STYLE'].includes(node.tagName)) return;
    for (const attribute of ['aria-label', 'alt', 'title', 'placeholder']) {
      const value = node.getAttribute(attribute);
      if (value != null) {
        const translated = translate(value);
        if (value !== translated) node.setAttribute(attribute, translated);
      }
    }
    node.childNodes.forEach(localize);
  }

  if (code === 'en') {
    document.documentElement.lang = code;
    document.title = translate(document.title);
    localize(document.body);
    new MutationObserver(changes => {
      for (const change of changes) {
        if (change.type === 'childList') change.addedNodes.forEach(localize);
        else localize(change.target);
      }
    }).observe(document.body, {
      subtree: true, childList: true, characterData: true,
      attributes: true, attributeFilter: ['aria-label', 'alt', 'title', 'placeholder'],
    });
    const confirm = window.confirm.bind(window);
    window.confirm = message => confirm(translate(String(message)));
  }

  return { code, localize };
